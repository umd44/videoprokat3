; Программа для чередования массивов A и B в массив C на ассемблере микроЭВМ-2
; Задача: Сформировать массив C из чередующихся элементов массивов A и B
; C(1)=A(1), C(2)=B(1), C(3)=A(2), C(4)=B(2), ..., C(2*n-1)=A(n), C(2*n)=B(n)

; Архитектура микроЭВМ-2:
; - Индексная адресация D(B) - адрес = D + содержимое(B)
; - Где D - смещение (константа/адрес), B - содержимое переменной служит как базовый адрес

; ===== СЕКЦИЯ ДАННЫХ =====
DATA
    ; Служебные переменные
    N:          0           ; Количество элементов в массивах A и B
    INDEX_A:    0           ; Индекс для массива A
    INDEX_B:    0           ; Индекс для массива B
    INDEX_C:    0           ; Индекс для массива C
    TEMP_VALUE: 0           ; Временная переменная для хранения значения
    BASE_ADDR:  0           ; Базовый адрес для индексной адресации
    
    ; Максимум 32 элемента в каждом массиве (с учетом ограничения 6 бит)
    A:          DS 32       ; Массив A (зарезервировано 32 ячейки)
    B:          DS 32       ; Массив B (зарезервировано 32 ячейки)
    C:          DS 64       ; Массив C (зарезервировано 64 ячейки для 2*N элементов)

; ===== ОСНОВНАЯ ПРОГРАММА =====
CODE
    ; ===== БЛОК ИНИЦИАЛИЗАЦИИ - ВВОД N =====
    INIT_N:
        IN                  ; Ввод количества элементов N
        ST  N               ; Сохранить в переменную N
        
    ; ===== БЛОК ВВОДА МАССИВА A =====
    INPUT_A:
        LDA 0               ; Инициализировать аккумулятор на 0
        ST  INDEX_A         ; INDEX_A = 0
        
    LOOP_A:
        LD  INDEX_A         ; Загрузить текущий индекс A
        SUB N               ; Вычесть N из INDEX_A
        JN  READ_A_ELEM     ; Если результат < 0 (INDEX_A < N), читать элемент
        JMP INPUT_B         ; Иначе перейти к вводу массива B
        
    READ_A_ELEM:
        IN                  ; Ввод элемента массива A
        
        ; Использование индексной адресации D(B) для сохранения элемента
        ; ST A(INDEX_A) - сохранить в массив A с индексом INDEX_A
        LD  INDEX_A         ; Загрузить индекс в аккумулятор
        ST  BASE_ADDR       ; Сохранить индекс в BASE_ADDR для индексной адресации
        IN                  ; Ввод значения (оно будет в аккумуляторе)
        ST  A(BASE_ADDR)    ; Сохранить в A[INDEX_A] используя индексную адресацию
        
        ; Увеличить INDEX_A на 1
        LD  INDEX_A
        ADD 1
        ST  INDEX_A
        JMP LOOP_A
        
    ; ===== БЛОК ВВОДА МАССИВА B =====
    INPUT_B:
        LDA 0               ; Инициализировать аккумулятор на 0
        ST  INDEX_B         ; INDEX_B = 0
        
    LOOP_B:
        LD  INDEX_B         ; Загрузить текущий индекс B
        SUB N               ; Вычесть N из INDEX_B
        JN  READ_B_ELEM     ; Если результат < 0 (INDEX_B < N), читать элемент
        JMP INIT_PROCESS    ; Иначе перейти к инициализации обработки
        
    READ_B_ELEM:
        IN                  ; Ввод значения элемента массива B
        
        ; Использование индексной адресации
        LD  INDEX_B         ; Загрузить индекс в аккумулятор
        ST  BASE_ADDR       ; Сохранить индекс в BASE_ADDR для индексной адресации
        IN                  ; Ввод значения
        ST  B(BASE_ADDR)    ; Сохранить в B[INDEX_B] используя индексную адресацию
        
        ; Увеличить INDEX_B на 1
        LD  INDEX_B
        ADD 1
        ST  INDEX_B
        JMP LOOP_B
        
    ; ===== ИНИЦИАЛИЗАЦИЯ ОБРАБОТКИ =====
    INIT_PROCESS:
        LDA 0               ; Инициализировать на 0
        ST  INDEX_A         ; INDEX_A = 0
        ST  INDEX_B         ; INDEX_B = 0
        ST  INDEX_C         ; INDEX_C = 0
        
    ; ===== БЛОК ФОРМИРОВАНИЯ МАССИВА C =====
    ; Цикл для чередования элементов A и B в C
    LOOP_C:
        LD  INDEX_A         ; Загрузить INDEX_A
        SUB N               ; Вычесть N
        JN  COPY_A_ELEM     ; Если INDEX_A < N, копировать элемент из A
        JMP OUTPUT_C        ; Иначе перейти к выводу массива C
        
    COPY_A_ELEM:
        ; Копировать элемент A[INDEX_A] в C[INDEX_C]
        LD  INDEX_A         ; Загрузить индекс A
        ST  BASE_ADDR       ; Сохранить в BASE_ADDR
        LD  A(BASE_ADDR)    ; Загрузить элемент из массива A
        ST  TEMP_VALUE      ; Сохранить значение во временную переменную
        
        ; Сохранить в C[INDEX_C]
        LD  INDEX_C         ; Загрузить индекс C
        ST  BASE_ADDR       ; Сохранить в BASE_ADDR
        LD  TEMP_VALUE      ; Загрузить значение
        ST  C(BASE_ADDR)    ; Сохранить элемент в массив C
        
        ; Увеличить INDEX_C на 1
        LD  INDEX_C
        ADD 1
        ST  INDEX_C
        
        ; Копировать элемент B[INDEX_B] в C[INDEX_C]
        LD  INDEX_B         ; Загрузить индекс B
        ST  BASE_ADDR       ; Сохранить в BASE_ADDR
        LD  B(BASE_ADDR)    ; Загрузить элемент из массива B
        ST  TEMP_VALUE      ; Сохранить значение во временную переменную
        
        ; Сохранить в C[INDEX_C]
        LD  INDEX_C         ; Загрузить индекс C
        ST  BASE_ADDR       ; Сохранить в BASE_ADDR
        LD  TEMP_VALUE      ; Загрузить значение
        ST  C(BASE_ADDR)    ; Сохранить элемент в массив C
        
        ; Увеличить INDEX_C на 1
        LD  INDEX_C
        ADD 1
        ST  INDEX_C
        
        ; Увеличить INDEX_A и INDEX_B на 1
        LD  INDEX_A
        ADD 1
        ST  INDEX_A
        
        LD  INDEX_B
        ADD 1
        ST  INDEX_B
        
        JMP LOOP_C
        
    ; ===== БЛОК ВЫВОДА МАССИВА C =====
    OUTPUT_C:
        LDA 0               ; Инициализировать индекс на 0
        ST  INDEX_C         ; INDEX_C = 0
        
    ; Предварительно вычислить 2*N для сравнения
    CALC_2N:
        LD  N               ; Загрузить N
        ADD N               ; Удвоить (2*N)
        ST  TEMP_VALUE      ; Сохранить 2*N во временную переменную
        
    LOOP_OUTPUT:
        LD  INDEX_C         ; Загрузить INDEX_C
        SUB TEMP_VALUE      ; Вычесть 2*N
        JN  PRINT_C_ELEM    ; Если INDEX_C < 2*N, выводить элемент
        JMP END_PROGRAM     ; Иначе завершить программу
        
    PRINT_C_ELEM:
        ; Загрузить элемент C[INDEX_C] и вывести
        LD  INDEX_C         ; Загрузить индекс C
        ST  BASE_ADDR       ; Сохранить в BASE_ADDR
        LD  C(BASE_ADDR)    ; Загрузить элемент из массива C
        OUT                 ; Вывести элемент
        
        ; Увеличить INDEX_C на 1
        LD  INDEX_C
        ADD 1
        ST  INDEX_C
        JMP LOOP_OUTPUT
        
    ; ===== КОНЕЦ ПРОГРАММЫ =====
    END_PROGRAM:
        STOP                ; Остановить программу
